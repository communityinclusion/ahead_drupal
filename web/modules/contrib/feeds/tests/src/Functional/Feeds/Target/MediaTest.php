          'settings' => [
            'media_name' => 'entity_name',
          ],
        ],
        [
          'target' => 'title',
          'map' => ['value' => 'title'],
        ],
      ],
    ]);

    $feed = $this->createFeed($feed_type->id(), [
      'source' => $this->getBaseUrl() . '/testing/feeds/images.csv',
    ]);

    // Import one row and assert fallback media name is still populated.
    $feed->import();

    $this->assertNodeCount(1);
    $node = Node::load(1);
    $media_reference = $node->get('field_media')->entity;
