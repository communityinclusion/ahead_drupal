    // Create a media reference field on the node type under test.
    $this->createMediaField(['image' => 'image']);

    $csv_columns = [
      'title' => 'title',
      'file' => 'file',
    ];

    // Create a feed type with mapping to node title and the media field. For
    // the media field, we configure the media name to taken from the entity
    // name. The title mapping is done after the media mapping. This means that
    // the node will have no name yet at the time of processing the media. So in
    // that case, the media name will be taken from the file name. This behavior
    // is implemented by the Media module.
    $feed_type = $this->createFeedTypeForCsv($csv_columns, [
      'fetcher' => 'http',
      'fetcher_configuration' => [],
      'mappings' => [
        [
