  /**
   * Tests importing media into a media field.
   *
   * @param string $expected_filename
   *   The name of the file written to the file system after import.
   * @param array $target_bundles
   *   The type of media that the media field should support.
   * @param string $csv_filename
   *   The CSV file to import, generated by the feeds_test_files module.
   * @param string $media_field_name
   *   The field name on the media entity that references the file.
   *
   * @dataProvider mediaImportProvider
   */
  public function testMediaImportToMediaField(string $expected_filename, array $target_bundles, string $csv_filename, string $media_field_name): void {
    // Create a media reference field.
    $this->createMediaField($target_bundles);

    // Create a feed type for importing CSV files.
    $csv_columns = [
      'title' => 'title',
      'file' => 'file',
    ];
    $feed_type = $this->createFeedTypeForCsv($csv_columns, [
      'fetcher' => 'http',
      'fetcher_configuration' => [],
      'mappings' => [
        [
          'target' => 'title',
          'map' => ['value' => 'title'],
        ],
        [
          'target' => 'field_media',
          'map' => ['target_id' => 'file'],
        ],
      ],
    ]);

    // Create a feed and import.
    $feed = $this->createFeed($feed_type->id(), [
      'source' => $this->getBaseUrl() . '/testing/feeds/' . $csv_filename,
    ]);
    $feed->import();

    // Assert that a node got created.
    $this->assertNodeCount(1);

    // Load the first node and check if it contains a media entity.
    $node = Node::load(1);
    $media_reference = $node->get('field_media')->entity;
    $this->assertInstanceOf(Media::class, $media_reference, 'The referenced entity is a media entity.');
    $this->assertEquals(array_key_first($target_bundles), $media_reference->bundle(), 'The media entity has the expected bundle.');
    $file = $media_reference->get($media_field_name)->entity;
    $this->assertInstanceOf(File::class, $file, 'The media entity contains a file.');
    $this->assertEquals($expected_filename, $file->getFilename(), 'The file has the expected filename.');

    // Check if the file exists on the file system.
    $file_path = $this->container->get('file_system')->realpath('public://' . date('Y-m') . '/' . $expected_filename);
    $this->assertFileExists($file_path);

    // Check if the media is displayed on the media edit form.
    $this->drupalGet($media_reference->toUrl('edit-form'));
    $this->assertSession()->pageTextContains($expected_filename);
  }

