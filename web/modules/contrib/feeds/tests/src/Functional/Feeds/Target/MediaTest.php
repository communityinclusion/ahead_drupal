  /**
   * Tests that importing media multiple times does not create duplicates.
   */
  public function testMediaUpdateImportDoesNotCreateDuplicateEntities(): void {
    // Create a media reference field.
    $this->createMediaField(['image' => 'image']);

    // Create a feed type configured to update existing entities with force
    // update.
    $csv_columns = [
      'title' => 'title',
      'file' => 'file',
    ];
    $feed_type = $this->createFeedTypeForCsv($csv_columns, [
      'fetcher' => 'http',
      'fetcher_configuration' => [],
      'processor_configuration' => [
        'update_existing' => ProcessorInterface::UPDATE_EXISTING,
        'skip_hash_check' => TRUE,
        'values' => [
          'type' => 'article',
        ],
      ],
      'mappings' => [
        [
          'target' => 'title',
          'map' => ['value' => 'title'],
          'unique' => ['value' => TRUE],
        ],
        [
          'target' => 'field_media',
          'map' => ['target_id' => 'file'],
        ],
      ],
    ]);

    // Create a feed and import once.
    $feed = $this->createFeed($feed_type->id(), [
      'source' => $this->getBaseUrl() . '/testing/feeds/images.csv',
    ]);
    $feed->import();

    // Assert that a node got created.
    $this->assertNodeCount(1);

    // Load the node and check if it contains a media entity and file.
    $node = Node::load(1);
    $this->assertNotNull($node, 'A node was created.');
    $media = $node->get('field_media')->entity;
    $this->assertInstanceOf(Media::class, $media, 'The referenced entity is a media entity.');
    $file = $media->get('field_media_image')->entity;
    $this->assertInstanceOf(File::class, $file, 'The media entity contains a file.');

    // Store entity IDs and filename for comparison after second import.
    $node_id = $node->id();
    $media_id = $media->id();
    $file_id = $file->id();
    $expected_filename = $file->getFilename();
    $file_directory_uri = dirname($file->getFileUri());

    // Import the same feed a second time.
    $feed->import();

    // Assert entity counts.
    $this->assertNodeCount(1, 'Exactly 1 node should exist after second import.');
    $media_count = $this->container->get('entity_type.manager')->getStorage('media')
      ->getQuery()
      ->accessCheck(FALSE)
      ->count()
      ->execute();
    $this->assertEquals(1, $media_count, 'Exactly 1 media entity should exist after second import.');
    $file_count = $this->container->get('entity_type.manager')->getStorage('file')
      ->getQuery()
      ->accessCheck(FALSE)
      ->count()
      ->execute();
    $this->assertEquals(1, $file_count, 'Exactly 1 file entity should exist after second import.');

    // Assert that the node still reference the same media entity.
    $node = $this->reloadEntity($node);
    $this->assertEquals($media_id, $node->get('field_media')->target_id, 'The node should reference the same media entity ID.');

    // Assert that the media entity still references the same file.
    $media = $this->reloadEntity($media);
    $this->assertEquals($file_id, $media->get('field_media_image')->target_id, 'The media entity should reference the same file entity ID.');

    // Assert that the file entity points to a file with the exact same name.
    $file = $this->reloadEntity($file);
    $this->assertEquals($expected_filename, $file->getFilename(), 'The file entity should point to a file with the exact same name.');

    // Assert that only one file exists in the directory.
    $file_directory_realpath = $this->container->get('file_system')->realpath($file_directory_uri);
    $files_in_directory = $this->container->get('file_system')->scanDirectory($file_directory_realpath, '/.*/');
    $this->assertCount(1, $files_in_directory, 'Exactly 1 file should exist in the file directory.');
  }

