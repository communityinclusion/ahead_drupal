  }

  /**
   * Imports by existing file ID with bad extension and expects validation fail.
   */
  public function testExistingFileIdWithInvalidMediaFieldExtension(): void {
    // Create a media reference field on the node type under test.
    $this->createMediaField(['image' => 'image']);

    // Pre-create a file entity whose extension is invalid for image media.
    $file_system = $this->container->get('file_system');
    $file_uri = 'public://existing-invalid.exe';
    $file_system->saveData('dummy', $file_uri);
    $file = File::create([
      'uri' => $file_uri,
      'status' => 1,
    ]);
    $file->save();

    // Create CSV that references the existing file ID.
    $csv_content = "title,file_id\nInvalid existing file,{$file->id()}\n";
    $csv_file_uri = 'public://test_media_existing_invalid_ext_' .
      $this->randomMachineName() . '.csv';
    $file_system->saveData($csv_content, $csv_file_uri);
    $csv_file_path = $file_system->realpath($csv_file_uri);

    $csv_columns = [
      'title' => 'title',
      'file_id' => 'file_id',
    ];

    // Configure media mapping to resolve by file ID from the CSV.
    $feed_type = $this->createFeedTypeForCsv($csv_columns, [
      'fetcher' => 'directory',
      'fetcher_configuration' => [
        'allowed_extensions' => 'csv',
      ],
      'mappings' => [
        [
          'target' => 'title',
          'map' => ['value' => 'title'],
        ],
        [
          'target' => 'field_media',
          'map' => ['target_id' => 'file_id'],
          'settings' => [
            'reference_by' => 'file_id',
          ],
        ],
      ],
    ]);

    $feed = $this->createFeed($feed_type->id(), [
      'source' => $csv_file_path,
    ]);

    // Run import through UI batch flow so the error message is rendered.
    $this->batchImport($feed);

    // Assert validation error and that no content item is imported.
    $this->assertSession()->pageTextContains('extension, exe, is invalid');

    // Ensure no media entity is created for invalid existing file extension.
    $media_count = $this->container->get('entity_type.manager')
      ->getStorage('media')
      ->getQuery()
      ->accessCheck(FALSE)
      ->count()
      ->execute();
    $this->assertEquals(0, $media_count, 'No media entities should be created.');

    // Keep only the pre-created file entity.
    $file_count = $this->container->get('entity_type.manager')
      ->getStorage('file')
      ->getQuery()
      ->accessCheck(FALSE)
      ->count()
      ->execute();
    $this->assertEquals(1, $file_count, 'Only the pre-created file should exist.');

    // Clean up temporary CSV source.
    $file_system->delete($csv_file_uri);
  }

