  /**
   * Tests that an existing media entity can be referenced using URL as input.
   *
   * This verifies that when reference_by is 'file_id' and the input is a URL
   * pointing to an already imported file, the system finds the existing media
   * entity instead of creating a duplicate.
   */
  public function testReferenceExistingMediaByFileIdWithUrl(): void {
    // Create a media reference field.
    $this->createMediaField(['image' => 'image']);

    // Set a static file directory on the media image field to avoid token
    // dependencies. This ensures the test doesn't break if core defaults
    // change.
    $field_config = \Drupal::entityTypeManager()->getStorage('field_config')->load('media.image.field_media_image');
    $settings = $field_config->getSettings();
    $settings['file_directory'] = 'test_media_files';
    $field_config->setSettings($settings);
    $field_config->save();

    // Create a file entity at the location where imports will save files.
    $file_directory = 'public://test_media_files';
    $file_system = $this->container->get('file_system');
    $file_system->prepareDirectory($file_directory, FileSystemInterface::CREATE_DIRECTORY);

    // Create a file entity at the same location where imports will save files.
    $file_uri = $file_directory . '/tubing.jpeg';
    $file_system->copy($this->resourcesPath() . '/assets/tubing.jpeg', $file_uri);
    $file = File::create([
      'uri' => $file_uri,
      'status' => 1,
    ]);
    $file->save();

    // Create an existing media entity.
    $existing_media = Media::create([
      'bundle' => 'image',
      'name' => 'Existing Media Entity',
      'field_media_image' => [
        'target_id' => $file->id(),
        'alt' => 'Test image',
      ],
    ]);
    $existing_media->save();

    $existing_media_id = $existing_media->id();
    $existing_file_id = $file->id();

    // Create a CSV file with a URL pointing to the same file.
    $assets_url = $this->resourcesUrl() . '/assets';
    $csv_content = "title,file_url\n";
    $csv_content .= "Test Node,{$assets_url}/tubing.jpeg\n";
    $csv_file_uri = 'public://test_media_url_existing_' . $this->randomMachineName() . '.csv';
    $file_system->saveData($csv_content, $csv_file_uri);
    $csv_file_path = $file_system->realpath($csv_file_uri);

    // Create a feed type with reference_by set to 'file_id'.
    $csv_columns = [
      'title' => 'title',
      'file_url' => 'file_url',
    ];
    $feed_type = $this->createFeedTypeForCsv($csv_columns, [
      'fetcher' => 'directory',
      'fetcher_configuration' => [
        'allowed_extensions' => 'csv',
      ],
      'mappings' => [
        [
          'target' => 'title',
          'map' => ['value' => 'title'],
        ],
        [
          'target' => 'field_media',
          'map' => ['target_id' => 'file_url'],
          'settings' => [
            'reference_by' => 'file_id',
          ],
        ],
      ],
    ]);

    // Create a feed and import.
    $feed = $this->createFeed($feed_type->id(), [
      'source' => $csv_file_path,
    ]);
    $feed->import();

    // Assert that a node was created.
    $this->assertNodeCount(1);

    // Load the node and verify it references the existing media entity.
    $node = Node::load(1);
    $this->assertNotNull($node, 'A node was created.');
    $referenced_media = $node->get('field_media')->entity;
    $this->assertInstanceOf(Media::class, $referenced_media, 'The node references a media entity.');
    $this->assertEquals($existing_media_id, $referenced_media->id(), 'The node references the existing media entity, not a new one.');

    // Verify that the media entity still references the same file.
    $referenced_file = $referenced_media->get('field_media_image')->entity;
    $this->assertInstanceOf(File::class, $referenced_file, 'The media entity contains a file.');
    $this->assertEquals($existing_file_id, $referenced_file->id(), 'The media entity references the existing file, not a new one.');

    // Verify that no new media entity was created.
    $media_count = $this->container->get('entity_type.manager')->getStorage('media')
      ->getQuery()
      ->accessCheck(FALSE)
      ->count()
      ->execute();
    $this->assertEquals(1, $media_count, 'Exactly 1 media entity should exist (the original one).');

    // Verify that no new file entity was created (should reuse existing file).
    $file_count = $this->container->get('entity_type.manager')->getStorage('file')
      ->getQuery()
      ->accessCheck(FALSE)
      ->count()
      ->execute();
    $this->assertEquals(1, $file_count, 'Exactly 1 file entity should exist (the original one).');

