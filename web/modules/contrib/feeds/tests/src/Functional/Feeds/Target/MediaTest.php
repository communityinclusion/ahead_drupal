  /**
   * Tests that an existing media entity can be referenced.
   *
   * @param string $reference_by
   *   The field to reference by (mid, name, or file_id).
   * @param string $csv_column_name
   *   The CSV column name for the reference value.
   * @param string $csv_value_getter
   *   The method name to get the CSV value from the created media.
   *
   * @dataProvider existingMediaReferenceProvider
   */
  public function testReferenceExistingMedia(string $reference_by, string $csv_column_name, string $csv_value_getter): void {
    // Create a media reference field.
    $this->createMediaField(['image' => 'image']);

    // Create a file entity first.
    $file_uri = 'public://tubing.jpeg';
    $file_system = $this->container->get('file_system');
    $file_system->copy($this->resourcesPath() . '/assets/tubing.jpeg', $file_uri);
    $file = File::create([
      'uri' => $file_uri,
      'status' => 1,
    ]);
    $file->save();

    // Create an existing media entity.
    $media = Media::create([
      'bundle' => 'image',
      'name' => 'Test Media Entity',
      'field_media_image' => [
        'target_id' => $file->id(),
        'alt' => 'Test image',
      ],
    ]);
    $media->save();

    // Get the reference value based on the reference method.
    $reference_value = $this->{$csv_value_getter}($media, $file);

    // Create a CSV file with the reference value.
    $csv_content = "title,{$csv_column_name}\n";
    $csv_content .= "Test Node,{$reference_value}\n";
    $csv_file_uri = 'public://test_media_reference_' . $this->randomMachineName() . '.csv';
    $file_system->saveData($csv_content, $csv_file_uri);
    $csv_file_path = $file_system->realpath($csv_file_uri);

    // Create a feed type.
    $csv_columns = [
      'title' => 'title',
      $csv_column_name => $csv_column_name,
    ];
    $feed_type = $this->createFeedTypeForCsv($csv_columns, [
      'fetcher' => 'directory',
      'fetcher_configuration' => [
        'allowed_extensions' => 'csv',
      ],
      'mappings' => [
        [
          'target' => 'title',
          'map' => ['value' => 'title'],
        ],
        [
          'target' => 'field_media',
          'map' => ['target_id' => $csv_column_name],
          'settings' => [
            'reference_by' => $reference_by,
          ],
        ],
      ],
    ]);

    // Create a feed and import.
    $feed = $this->createFeed($feed_type->id(), [
      'source' => $csv_file_path,
    ]);
    $feed->import();

    // Assert that a node was created.
    $this->assertNodeCount(1);

    // Load the node and verify it references the existing media entity.
    $node = Node::load(1);
    $this->assertNotNull($node, 'A node was created.');
    $referenced_media = $node->get('field_media')->entity;
    $this->assertInstanceOf(Media::class, $referenced_media, 'The node references a media entity.');
    $this->assertEquals($media->id(), $referenced_media->id(), 'The node references the existing media entity.');

    // Verify that no new media entity was created.
    $media_count = $this->container->get('entity_type.manager')->getStorage('media')
      ->getQuery()
      ->accessCheck(FALSE)
      ->count()
      ->execute();
    $this->assertEquals(1, $media_count, 'Exactly 1 media entity should exist.');

    // Clean up the CSV file.
    $file_system->delete($csv_file_uri);
  }

